function evaluateActiveTransferParaphrase({
  sourceSentence,
  studentRewrite,
  modelRewrite,
  targetNominals = []
}) {
  const cleanSource = String(sourceSentence || '').trim();
  const cleanStudent = String(studentRewrite || '').trim();
  const studentWords = cleanStudent.toLowerCase().split(/\s+/).filter(Boolean);
  const sourceWords = new Set(
    cleanSource
      .toLowerCase()
      .replace(/[^a-z0-9\s]/g, '')
      .split(/\s+/)
      .filter((w) => w.length > 4)
  );

  // Measure nominalization suffixes (-tion, -sion, -ment, -ity, -ance, -ence, -cy, -ism)
  const nominalRegex = /\b[a-z]+(tion|sion|ment|ity|ance|ence|cy|ism|ship|tude)s?\b/gi;
  const detectedNominals = Array.from(
    new Set((cleanStudent.match(nominalRegex) || []).map((w) => w.toLowerCase()))
  );

  // Measure lexical variety / non-lifting
  const overlapCount = studentWords.filter((w) => sourceWords.has(w.replace(/[^a-z0-9]/g, ''))).length;
  const paraphraseRatio =
    studentWords.length > 0
      ? Math.max(0, Math.min(100, Math.round((1 - overlapCount / (studentWords.length + 3)) * 100)))
      : 0;

  const nominalBonus = Math.min(30, detectedNominals.length * 10);
  const lengthBonus = studentWords.length >= 10 ? 68 : studentWords.length >= 5 ? 52 : 30;
  const overallScore = Math.min(98, Math.max(45, Math.round(lengthBonus + nominalBonus * 0.8 + paraphraseRatio * 0.15)));

  const cefrLevel =
    overallScore >= 88
      ? 'C2 Academic Mastery'
      : overallScore >= 75
      ? 'C1+ Advanced Nominalization'
      : 'B2/C1 Developing Paraphrase';

  return {
    overallScore,
    cefrLevel,
    paraphraseRatio,
    detectedNominals:
      detectedNominals.length > 0 ? detectedNominals : targetNominals.slice(0, 2),
    feedbackVi:
      detectedNominals.length >= 2
        ? `Xuất sắc! Bạn đã áp dụng kỹ thuật Danh hóa (Nominalization: ${detectedNominals.join(
            ', '
          )}) để nén mệnh đề động từ thành cụm danh từ học thuật C2 súc tích.`
        : `Câu viết lại đã diễn đạt đúng ý gốc. Để đạt chuẩn C2 HSGQG, hãy chuyển các động từ/tính từ chính thành Cụm danh từ trừu tượng (Nominalization: ${
            targetNominals.join(', ') || 'proliferation, consolidation, entrenchment'
          }) làm chủ ngữ hoặc tân ngữ cho động từ học thuật (precipitate, engender, exacerbate).`,
    modelC2Rewrite:
      modelRewrite ||
      'The unfettered proliferation of algorithmic mediation risks precipitating the gradual atrophy of autonomous cognitive synthesis.'
  };
}

